import AppKit
import Darwin
import CloakToolsCore
import Observation
import UniformTypeIdentifiers

@MainActor @Observable
final class AutomaticOptimization {
    private(set) var clipboardStatus: String?
    private var clipboardLoop: Task<Void, Never>?
    private struct Watch {
        let rule: OptimizationFolderRule
        let options: OptimizationOptions
        let task: Task<Void, Never>
    }
    private var watches: [UUID: Watch] = [:]
    private(set) var activeRules: Set<UUID> = []
    private(set) var ruleStatus: [UUID: String] = [:]
    var didSave: ((URL, Int, Int) -> Void)?

    func configure(clipboard: Bool, rules: [OptimizationFolderRule], recipes: [ExportRecipe]) {
        if clipboard && clipboardLoop == nil {
            let initialCount = NSPasteboard.general.changeCount
            clipboardLoop = Task { [weak self] in
                var seen = initialCount
                while !Task.isCancelled {
                    do { try await Task.sleep(for: .milliseconds(650)) } catch { break }
                    guard let self else { break }
                    let board = NSPasteboard.general
                    let count = board.changeCount
                    guard count != seen else { continue }
                    seen = count
                    do {
                        if try await self.optimizeClipboard(board, generation: count) { seen = board.changeCount }
                    } catch is CancellationError { break }
                    catch OptimizationError.noReduction { self.clipboardStatus = "Copied image is already compact." }
                    catch { if !Task.isCancelled { self.clipboardStatus = error.localizedDescription } }
                }
            }
        } else if !clipboard {
            clipboardLoop?.cancel()
            clipboardLoop = nil
            clipboardStatus = nil
        }
        let ids = Set(rules.map(\.id))
        for id in Array(watches.keys) where !ids.contains(id) { stop(id) }
        ruleStatus = ruleStatus.filter { ids.contains($0.key) }
        for rule in rules {
            let options: OptimizationOptions
            if let id = rule.recipeID {
                guard let recipe = recipes.first(where: { $0.id == id }), case let .optimize(saved) = recipe.options else {
                    stop(rule.id)
                    ruleStatus[rule.id] = "Recipe unavailable. Edit this rule to resume."
                    continue
                }
                options = saved
            } else { options = OptimizationOptions() }
            if let watch = watches[rule.id], watch.rule == rule, watch.options == options { continue }
            stop(rule.id)
            let task = Task { [weak self] in
                guard let self else { return }
                await watch(rule, options: options)
                if !Task.isCancelled { activeRules.remove(rule.id) }
            }
            watches[rule.id] = Watch(rule: rule, options: options, task: task)
        }
    }

    func retryStoppedRule(_ id: UUID) {
        if !activeRules.contains(id), ruleStatus[id] != nil { stop(id) }
    }

    private func stop(_ id: UUID) {
        watches.removeValue(forKey: id)?.task.cancel()
        activeRules.remove(id)
        ruleStatus[id] = nil
    }

    /// Ignore file references and any item explicitly marked transient, generated or confidential.
    func optimizeClipboard(_ board: NSPasteboard, generation: Int) async throws -> Bool {
        guard let item = board.pasteboardItems?.onlyItem, board.changeCount == generation else { return false }
        let excluded = [NSPasteboard.PasteboardType.fileURL.rawValue, "org.nspasteboard.ConcealedType",
                        "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        guard !item.types.contains(where: { excluded.contains($0.rawValue) }) else { return false }
        guard let type = [.png, NSPasteboard.PasteboardType(UTType.jpeg.identifier), .tiff].first(where: item.types.contains),
              let bytes = item.data(forType: type), board.changeCount == generation else { return false }
        let task = Task.detached(priority: .utility) {
            let result = try await MediaOptimization.clipboardImage(bytes)
            let data = try Data(contentsOf: result.previewURL)
            return (data, result.previewURL.pathExtension)
        }
        let (data, ext) = try await withTaskCancellationHandler(operation: { try await task.value }, onCancel: { task.cancel() })
        try Task.checkCancellation()
        guard board.changeCount == generation, let output = UTType(filenameExtension: ext) else { return false }
        let replacement = NSPasteboardItem()
        replacement.setData(data, forType: .init(output.identifier))
        replacement.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType"))
        board.clearContents()
        guard board.writeObjects([replacement]) else { throw ClipboardError.unavailable }
        clipboardStatus = "Copied image reduced to \(ByteCountFormatter.string(fromByteCount: Int64(data.count), countStyle: .file))."
        return true
    }

    private func watch(_ rule: OptimizationFolderRule, options: OptimizationOptions) async {
        let folder = rule.folder
        do {
            let (events, source) = try directoryEvents(folder)
            defer { source.cancel() }
            let descriptor = source.handle
            var iterator = events.makeAsyncIterator()
            var state = WatchedMedia(baseline: try await scan(folder, descriptor: descriptor))
            try Task.checkCancellation()
            activeRules.insert(rule.id)
            while !Task.isCancelled {
                if state.hasPending { try await Task.sleep(for: .seconds(3)) }
                else if await iterator.next() == nil { return }
                try Task.checkCancellation()
                let snapshot = try await scan(folder, descriptor: descriptor)
                for url in state.stableAdditions(snapshot) where rule.kind.accepts(url) {
                    try Task.checkCancellation()
                    do {
                        let result = try await MediaOptimization.prepare(url, options: options)
                        try Task.checkCancellation()
                        guard let original = snapshot[url], try WatchedMedia.stamp(url) == original else {
                            state.reconsider(url)
                            continue
                        }
                        let worker = Task.detached(priority: .utility) {
                            try Self.verifyFolder(folder, descriptor: descriptor)
                            return try result.save(in: WatchedMedia.outputFolder(for: folder))
                        }
                        let output = try await withTaskCancellationHandler(operation: { try await worker.value }, onCancel: { worker.cancel() })
                        didSave?(output, result.inputBytes, result.outputBytes)
                        try Task.checkCancellation()
                        ruleStatus[rule.id] = "Saved \(output.lastPathComponent)."
                    } catch is CancellationError { return }
                    catch {
                        try Task.checkCancellation()
                        try Self.verifyFolder(folder, descriptor: descriptor)
                        if (try? WatchedMedia.stamp(url)) != snapshot[url] { state.reconsider(url) }
                        ruleStatus[rule.id] = "\(url.lastPathComponent) · \(error.localizedDescription)"
                    }
                }
            }
        } catch is CancellationError { }
        catch { if !Task.isCancelled { ruleStatus[rule.id] = "Folder monitoring stopped. \(error.localizedDescription)" } }
    }
    private nonisolated func directoryEvents(_ folder: URL) throws -> (AsyncStream<Void>, DispatchSourceFileSystemObject) {
        let fd = open(folder.path, O_EVTONLY | O_NOFOLLOW | O_DIRECTORY)
        guard fd >= 0 else { throw ToolError.unavailableFolder }
        let source = DispatchSource.makeFileSystemObjectSource(fileDescriptor: fd, eventMask: [.write, .rename, .delete, .revoke], queue: .global(qos: .utility))
        let stream = AsyncStream<Void>(bufferingPolicy: .bufferingNewest(1)) { events in
            source.setEventHandler { events.yield(()) }
            source.setCancelHandler { Darwin.close(fd) }
            source.resume()
        }
        return (stream, source)
    }
    // Directory events follow the vnode. Enumeration follows the path, which can
    // now name a different directory after a rename or atomic replacement.
    private nonisolated static func verifyFolder(_ folder: URL, descriptor: Int32) throws {
        var observed = stat(), current = stat()
        guard fstat(descriptor, &observed) == 0, lstat(folder.path, &current) == 0,
              observed.st_dev == current.st_dev, observed.st_ino == current.st_ino else {
            throw FolderWorkflowError("The watched folder moved or was replaced. Choose the folder again in General settings.")
        }
    }

    private nonisolated func scan(_ folder: URL, descriptor: Int32) async throws -> WatchedMedia.Snapshot {
        try Self.verifyFolder(folder, descriptor: descriptor)
        let snapshot = try WatchedMedia.snapshot(in: folder)
        try Self.verifyFolder(folder, descriptor: descriptor)
        return snapshot
    }
}

private extension Array {
    var onlyItem: Element? { count == 1 ? first : nil }
}
