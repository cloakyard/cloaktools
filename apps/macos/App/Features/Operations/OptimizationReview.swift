import AppKit
import CloakToolsCore
import SwiftUI
import UniformTypeIdentifiers

enum OptimizationInput: Sendable {
    case file(URL)
    case clipboard(Data)

    var name: String {
        switch self {
        case let .file(url): url.lastPathComponent
        case .clipboard: "Clipboard Image"
        }
    }

    enum Kind { case image, pdf, video, audio }
    var kind: Kind {
        guard case let .file(url) = self else { return .image }
        let ext = url.pathExtension.lowercased()
        if ext == "pdf" { return .pdf }
        if MediaOptimization.audioExtensions.contains(ext) { return .audio }
        return MediaOptimization.imageExtensions.contains(ext) ? .image : .video
    }

    func prepare(_ options: OptimizationOptions) async throws -> OptimizedMedia {
        switch self {
        case let .file(url): try await MediaOptimization.prepare(url, options: options)
        case let .clipboard(bytes): try MediaOptimization.clipboardImage(bytes, options: options)
        }
    }
}

struct OptimizationRow: Identifiable {
    let id = UUID()
    let input: OptimizationInput
    var result: OptimizedMedia?
    var output: URL?
    var message: String?
    var backup: OptimizationBackup?
    var originalRemoved = false
}

@MainActor @Observable
final class OptimizationReview {
    let task = FolderTask()
    private(set) var rows: [OptimizationRow] = []
    private(set) var current: String?
    var recipe: ExportRecipe?
    var options = OptimizationOptions() {
        didSet {
            if options != oldValue {
                for i in rows.indices {
                    if rows[i].backup != nil || rows[i].originalRemoved { continue }
                    rows[i].result = nil
                    rows[i].message = nil
                    rows[i].output = nil
                }
                task.notice = nil
                task.error = nil
            }
        }
    }
    var readyCount: Int { rows.filter { $0.result != nil && $0.output == nil }.count }
    var pendingCount: Int { rows.filter { $0.result == nil && $0.message == nil && $0.output == nil }.count }

    func includes(_ kind: OptimizationInput.Kind) -> Bool { rows.isEmpty || rows.contains { $0.input.kind == kind } }

    func copyImage(_ result: OptimizedMedia) {
        do {
            let data = try Data(contentsOf: result.previewURL)
            guard let format = UTType(filenameExtension: result.previewURL.pathExtension), format.conforms(to: .image) else { throw OptimizationError.unsupported }
            let item = NSPasteboardItem()
            item.setData(data, forType: .init(format.identifier))
            item.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType"))
            NSPasteboard.general.clearContents()
            guard NSPasteboard.general.writeObjects([item]) else { throw ClipboardError.unavailable }
            task.notice = "Copied the optimized image."
        } catch { task.error = error.localizedDescription }
    }

    func add(_ urls: [URL]) {
        guard !urls.isEmpty else { return }
        var seen = Set(rows.compactMap { if case let .file(url) = $0.input { url } else { nil } })
        let unique = urls.map(\.standardizedFileURL).filter { seen.insert($0).inserted }
        guard rows.count + unique.count <= MediaOptimization.maximumItems else {
            task.error = "Add up to \(MediaOptimization.maximumItems) files per batch."
            return
        }
        rows.append(contentsOf: unique.map { OptimizationRow(input: .file($0)) })
        task.error = nil
    }

    func addClipboard() {
        guard !task.busy else { return }
        do {
            let board = NSPasteboard.general
            let files = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
            if !files.isEmpty { add(files); return }
            guard case let .image(bytes) = try ClipboardCapture.read() else { throw OptimizationError.unsupported }
            guard rows.count < MediaOptimization.maximumItems else {
                task.error = "This batch is full."
                return
            }
            // Retain at most one raw clipboard snapshot between runs.
            rows.removeAll { if case .clipboard = $0.input { true } else { false } }
            rows.append(.init(input: .clipboard(bytes)))
            task.error = nil
        } catch { task.error = error.localizedDescription }
    }

    func chooseFiles() {
        let panel = NSOpenPanel()
        panel.title = "Choose media to optimize"
        panel.prompt = "Add Files"
        panel.allowsMultipleSelection = true
        panel.allowedContentTypes = MediaOptimization.extensions.sorted().compactMap { UTType(filenameExtension: $0) }
        if panel.runModal() == .OK { add(panel.urls) }
    }

    func remove(_ id: UUID) {
        guard !task.busy else { return }
        rows.removeAll { $0.id == id }
    }

    func preview() {
        let pending = rows.filter { $0.output == nil && $0.result == nil }.map { ($0.id, $0.input) }
        let options = options
        guard !task.busy, !pending.isEmpty else { return }
        task.run("Preparing previews…", work: { [self] in
            for (id, input) in pending {
                try Task.checkCancellation()
                await started(input.name, id: id)
                do {
                    let result = try await input.prepare(options)
                    try Task.checkCancellation()
                    await prepared(result, id: id)
                } catch is CancellationError { throw CancellationError() }
                catch { await failed(error.localizedDescription, id: id) }
            }
        }, success: { }, finished: { self.current = nil })
    }

    func replaceOriginal(_ row: OptimizationRow) {
        guard let result = row.result, row.backup == nil else { return }
        task.run("Keeping original and replacing file…", work: { try result.replaceOriginal() }) { backup in
            guard let index = self.rows.firstIndex(where: { $0.id == row.id }) else { return }
            self.rows[index].output = backup.originalURL
            self.rows[index].backup = backup
            self.rows[index].message = "Original kept in \(backup.backupURL.deletingLastPathComponent().lastPathComponent)."
        }
    }
    func restoreOriginal(_ row: OptimizationRow) {
        guard let backup = row.backup else { return }
        task.run("Restoring original…", work: { try backup.restore() }) {
            guard let index = self.rows.firstIndex(where: { $0.id == row.id }) else { return }
            self.rows[index].backup = nil
            self.rows[index].output = backup.backupURL
            self.rows[index].message = "Original restored. Optimized copy kept separately."
        }
    }
    func trashOriginal(_ row: OptimizationRow) {
        guard let result = row.result, let copy = row.output, row.backup == nil else { return }
        task.run("Moving original to Trash…", work: { try result.trashOriginal(afterSaving: copy) }) {
            guard let index = self.rows.firstIndex(where: { $0.id == row.id }) else { return }
            self.rows[index].originalRemoved = true
            self.rows[index].message = "Original moved to Trash."
        }
    }

    func save(in folder: URL) {
        let pending = rows.compactMap { row in row.output == nil ? row.result.map { (row.id, $0) } : nil }
        guard !task.busy, !pending.isEmpty else { return }
        task.run("Saving copies…", work: { [self] in
            for (id, result) in pending {
                try Task.checkCancellation()
                await started(result.filename, id: id)
                do { await saved(try result.save(in: folder), id: id) }
                catch is CancellationError { throw CancellationError() }
                catch { await failed(error.localizedDescription, id: id) }
            }
        }, success: { }, finished: { self.current = nil })
    }

    private func started(_ name: String, id: UUID) {
        current = name
        if let index = rows.firstIndex(where: { $0.id == id }) { rows[index].message = nil }
    }
    private func prepared(_ result: OptimizedMedia, id: UUID) {
        if let index = rows.firstIndex(where: { $0.id == id }) { rows[index].result = result }
    }
    private func failed(_ reason: String, id: UUID) {
        if let index = rows.firstIndex(where: { $0.id == id }) { rows[index].message = reason }
    }
    private func saved(_ url: URL, id: UUID) {
        if let index = rows.firstIndex(where: { $0.id == id }) { rows[index].output = url }
    }
}
